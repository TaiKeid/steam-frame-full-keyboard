#!/usr/bin/env python3
"""Build emoji/emoji.tsv from Unicode's emoji-test.txt.

Each output line is one picker emoji: its group number (1 Smileys & Emotion to
9 Flags), the emoji, and its five skin-tone variants from light to dark, or
nothing when it takes no tone. Only fully-qualified emoji are kept, in the
file's CLDR order. A toned form is used only when every person in it has the
same tone; mixed tones are left out.
"""
import argparse
from pathlib import Path
import sys

GROUPS = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink",
          "Travel & Places", "Activities", "Objects", "Symbols", "Flags"]
TONES = [0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF]


def base_name(name):
    head, _, tail = name.partition(": ")
    rest = [part for part in tail.split(", ") if part and not part.endswith("skin tone")]
    return head + (": " + ", ".join(rest) if rest else "")


def build(lines):
    group = None
    entries, by_name = [], {}
    for line in lines:
        if line.startswith("# group: "):
            group = line[len("# group: "):].strip()
            continue
        if not line.strip() or line.startswith("#"):
            continue
        fields, _, comment = line.partition("#")
        points, _, status = fields.partition(";")
        if status.strip() != "fully-qualified" or group not in GROUPS:
            continue
        codes = [int(point, 16) for point in points.split()]
        text = "".join(map(chr, codes))
        name = comment.split(None, 2)[2].strip()  # Drop the emoji and its version.
        tones = {code for code in codes if code in TONES}
        if not tones:
            entry = [GROUPS.index(group) + 1, text, [""] * 5]
            entries.append(entry)
            by_name[name] = entry
        elif len(tones) == 1:
            base = by_name.get(base_name(name))
            if base is None:
                raise ValueError(f"no untoned form for {name}")
            base[2][TONES.index(tones.pop())] = text
    for entry in entries:
        if any(entry[2]) and not all(entry[2]):
            raise ValueError(f"incomplete tones for {entry[1]}")
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("emoji_test", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    lines = args.emoji_test.read_text(encoding="utf-8").splitlines()
    version = next(line.split(":", 1)[1].strip() for line in lines if line.startswith("# Version:"))
    out = [f"# Generated by tools/emoji_table.py from Unicode emoji-test.txt {version}; do not edit."]
    for group, text, tones in build(lines):
        out.append("\t".join([str(group), text, *(tones if any(tones) else [])]))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(out) - 1} emoji", file=sys.stderr)


if __name__ == "__main__":
    main()
