namespace framekeyboard {
// Picker categories in tab order: Recent, then Unicode's emoji groups
// without Component.
enum class EmojiGroup {
    Recent,
    Smileys,
    People,
    Animals,
    Food,
    Travel,
    Activities,
    Objects,
    Symbols,
    Flags
};
constexpr std::size_t emoji_group_count = 10;
Icon emoji_group_icon(EmojiGroup group);

struct EmojiEntry {
    EmojiGroup group{};
    std::string base;
    // Light to dark; empty when the emoji takes no skin tone.
    std::array<std::string, 5> tones;
    bool toned() const { return !tones[0].empty(); }
    // Tone 0 is the default yellow, 1 to 5 light to dark.
    const std::string& text(int tone) const;
};
struct EmojiCatalog {
    std::vector<EmojiEntry> entries; // CLDR order.
    const EmojiEntry* find(const std::string& base) const;
};
// The table generated by tools/emoji_table.py.
EmojiCatalog parse_emoji_table(std::string_view table);
const EmojiCatalog& bundled_emoji();

// Recent emoji and the chosen skin tone, kept beside the saved placement
// rather than in the settings. Recent emoji record what was typed, so they
// are never logged.
struct EmojiPreferences {
    static constexpr std::size_t max_recent = 64;
    std::vector<std::string> recent; // Untoned, most recent first.
    int tone{};
    bool operator==(const EmojiPreferences&) const = default;
};
// A missing or damaged file gives the defaults.
EmojiPreferences load_emoji_preferences(const std::filesystem::path& path);
void save_emoji_preferences(const std::filesystem::path& path, const EmojiPreferences& preferences);
void remember_emoji(EmojiPreferences& preferences, const std::string& base);

// The picker's keys, generated from the main layout in its own coordinates
// so both share one scale: its side column with the emoji key turned into
// Back, a space bar under the grid, and Backspace, Enter and the arrows at
// the right of the visible width. Hidden numpad space stays empty.
struct EmojiLayout {
    Layout layout;
    Rect tabs, grid; // Layout coordinates.
};
EmojiLayout emoji_layout(const Layout& main, double visible_width);

// What the panel draws for the picker, in panel coordinates.
struct EmojiPickerView {
    struct Cell {
        Rect bounds;
        std::string text;
        bool clear{}, hovered{}, pressed{};
        bool operator==(const Cell&) const = default;
    };
    struct Tab {
        Rect bounds;
        Icon icon{Icon::None};
        bool active{}, hovered{}, pressed{};
        bool operator==(const Tab&) const = default;
    };
    struct Popup {
        Rect bounds;
        std::vector<Cell> choices;
        bool operator==(const Popup&) const = default;
    };
    double width{}; // Visible layout width, which sets the case.
    Rect grid, tabs, scrolling_tabs;
    std::vector<Tab> tab_list;
    std::vector<Cell> cells; // Only those in view.
    std::string hint;
    Rect hint_bounds;
    std::optional<Popup> popup;
    std::uint64_t glyphs{}; // Changes when new emoji images are ready.
    bool operator==(const EmojiPickerView&) const = default;
};

// The picker's grid and tabs: one strip of every category, filled down each
// column and then across, scrolled sideways by dragging or with the stick.
// An emoji types when released over the cell it was pressed on; holding a
// toned one opens its skin tones instead. Panel coordinates throughout.
class EmojiPicker {
  public:
    struct Event {
        bool redraw{}, haptic{}, clear{};
        std::string type;          // Text to type.
        const EmojiEntry* typed{}; // Its entry, for the recent list.
        bool recent{};             // Chosen in Recent, which then keeps its order.
        std::optional<int> tone;   // A newly chosen skin tone.
    };
    void set_geometry(Rect tabs, Rect grid);
    // Sections in tab order; Recent first, which always takes six columns and
    // shows Clear in its bottom-right cell when not empty.
    // Loading shows only a hint until the emoji font has been checked.
    void set_content(std::array<std::vector<const EmojiEntry*>, emoji_group_count> sections, int tone,
                     bool loading);
    void set_tone(int tone);
    void set_glyphs(std::uint64_t generation) { glyphs_ = generation; }
    // Back to the first category, with nothing pressed.
    void reset();
    bool contains(double x, double y) const;
    Event down(unsigned pointer, double x, double y, double now);
    Event move(unsigned pointer, double x, double y);
    Event up(unsigned pointer, double x, double y);
    // Opens the skin tones of a held emoji.
    Event tick(double now);
    // Stick or wheel notches; positive scrolls toward later categories.
    bool scroll(double x, double y, double steps);
    void cancel_pointer(unsigned pointer);
    void cancel();
    bool pressed(unsigned pointer) const { return press_ && press_->pointer == pointer; }
    std::optional<unsigned> press_pointer() const {
        return press_ ? std::optional<unsigned>(press_->pointer) : std::nullopt;
    }
    bool popup_open() const { return press_ && press_->popup; }
    EmojiPickerView view() const;
    // Display texts for the glyph cache: those in view first, then outward.
    std::vector<std::string> glyph_order() const;
    // Where in the strip the view starts, for requesting glyphs only on change.
    int first_column() const;
    // Recent holds six columns, less the cell for Clear.
    static constexpr int recent_columns = 6;
    std::size_t recent_capacity() const { return static_cast<std::size_t>(recent_columns * rows_ - 1); }
    int glyph_size() const;
    double scroll_offset() const { return scroll_; }
    double scroll_limit() const;

  private:
    struct Item {
        const EmojiEntry* entry{}; // None for Clear.
        std::size_t group{};
        int column{}, row{}; // Column within the whole strip.
    };
    struct Section {
        double start{}; // Strip x of the first column.
        int first_column{}, columns{};
        std::size_t first_item{}, items{};
        bool shown{};
    };
    enum class Target { None, Cell, Tab, Choice };
    struct Hit {
        Target target{Target::None};
        std::size_t index{};
        bool operator==(const Hit&) const = default;
    };
    struct Press {
        unsigned pointer{};
        double x{}, y{}, scroll{}, tab_scroll{}, at{};
        Hit hit;
        bool dragging{}, popup{};
        std::optional<std::size_t> choice;
    };
    void layout_items();
    Hit hit(double x, double y) const;
    Rect cell_bounds(const Item& item) const;
    std::vector<std::size_t> shown_groups() const;
    double tab_width() const;
    // Recent stays at the left; the other tabs scroll beside it if they don't fit.
    Rect scrolling_tabs() const;
    Rect tab_bounds(std::size_t group) const;
    double tab_limit() const;
    std::size_t active_group() const;
    void reveal_tab(std::size_t group);
    std::optional<Rect> popup_bounds() const;
    Rect choice_bounds(std::size_t choice) const;
    std::string text(const Item& item) const;
    Rect tabs_{}, grid_{};
    int rows_{5};
    double cell_{};
    std::array<std::vector<const EmojiEntry*>, emoji_group_count> sections_{};
    std::array<Section, emoji_group_count> layout_{};
    std::vector<Item> items_;
    int tone_{};
    bool loading_{true};
    double scroll_{}, tab_scroll_{}, width_{};
    std::optional<std::size_t> chosen_group_; // A tapped tab, until the next manual scroll.
    std::optional<Press> press_;
    std::map<unsigned, Hit> hovered_;
    std::uint64_t glyphs_{};
};
} // namespace framekeyboard
